/// Result of reachability analysis.
///
/// Three possible outcomes:
/// - `Reachable`: the target is definitely reachable, with a witness.
/// - `Unreachable`: the target is definitely unreachable, with a proof.
/// - `Inconclusive`: current algorithms could not decide (e.g., unbounded
///   general net where LP/ILP filters pass but full exploration is infinite).
#[derive(Debug, Clone)]
pub enum ReachabilityResult {
    /// The target marking is reachable from M₀.
    Reachable(ReachabilityProof),
    /// The target marking is definitely not reachable from M₀.
    Unreachable(UnreachabilityProof),
    /// Current algorithms could not decide.
    Inconclusive,
}

impl ReachabilityResult {
    /// Whether the target is definitely reachable.
    #[must_use]
    pub const fn is_reachable(&self) -> bool {
        matches!(self, Self::Reachable(_))
    }

    /// Whether the target is definitely unreachable.
    #[must_use]
    pub const fn is_unreachable(&self) -> bool {
        matches!(self, Self::Unreachable(_))
    }
}

#[derive(Debug, Clone)]
pub enum ReachabilityProof {
    /// Valid for S-Systems (State Machines) that are strongly connected and M0(S) > 0.
    /// Proof relies on strict token conservation (Theorem 5.1.5).
    ///
    /// `marking_sum` is accumulated in `u64`: a token-conserving marking may hold
    /// more than `u32::MAX` tokens in total even when every place count fits in
    /// `u32`, so the conserved sum does not fit in `u32`.
    LiveStateMachineTokenConservation {
        marking_sum: u64,
    },

    /// Valid for T-Systems (Marked Graphs) that are live (all circuits marked).
    /// Proof relies on a non-negative integer solution to the marking equation (Theorem 5.2.7).
    LiveMarkedGraphMarkingEquationIntegerSolution(HashMap<Transition, u32>),

    /// Valid for Free-Choice systems that are live and bounded.
    /// Proof relies on an integer solution to the marking equation PLUS
    /// a proof that the subnet generated by the fired transitions has no unmarked traps (Theorem 5.3.18).
    LiveBoundedFreeChoiceMarkingEquationWithTrapCheck(HashMap<Transition, u32>),

    /// The universal fallback for non-live subclasses or general unrestricted nets.
    FiringSequence(Box<[Transition]>),
}

/// Proof that a marking is unreachable.
#[derive(Debug, Clone)]
#[non_exhaustive]
pub enum UnreachabilityProof {
    /// The net is an S-net (state machine): every transition preserves token count,
    /// so any marking with a different token sum than M₀ is unreachable.
    /// Requires no liveness or connectivity conditions.
    StateMachineTokenConservation,
    /// The LP marking equation (rational relaxation) is infeasible.
    /// Some S-invariant is violated.
    MarkingEquationNoRationalSolution,
    /// The ILP marking equation (integer) is infeasible.
    /// Stronger than LP: no integer firing count vector exists.
    MarkingEquationNoIntegerSolution,
    /// Full state space explored; target not found.
    ExhaustiveSearch,
}

impl From<ReachabilityProof> for ReachabilityResult {
    fn from(value: ReachabilityProof) -> Self {
        ReachabilityResult::Reachable(value)
    }
}

impl From<UnreachabilityProof> for ReachabilityResult {
    fn from(value: UnreachabilityProof) -> Self {
        ReachabilityResult::Unreachable(value)
    }
}

impl<N: AsRef<Net>> PetriNet<N> {
    /// If there is an efficient (polynomial-time) procedure to determine
    /// whether the given target marking is reachable in this Petri net,
    /// returns Some(_) with the answer.
    /// Returns None if the answer would not be efficient to compute.
    #[must_use]
    pub fn is_efficiently_reachable(&self, target: &Marking<u32>) -> Option<bool> {
        // todo: efficient check necessary for reachability: maximal unmarked trap in target must be unmarked in M0
        // Token conservation compares total token counts, accumulated in u64.
        // Summing in u32 overflows once a marking's total exceeds u32::MAX (even
        // when every place count individually fits in u32): a panic in debug, or
        // a silent wrap in release that could mint a false `reachable` verdict.
        let conserves_tokens = || {
            token_total(self.marking.iter())
                == token_total(target.support.iter().map(|(_, tokens)| tokens))
        };
        match self.class() {
            NetClass::Circuit => Some(conserves_tokens()),
            NetClass::StateMachine if self.is_live() => Some(conserves_tokens()),
            // NetClass::MarkedGraph if self.is_live() => Some(self.marking() ~ target) // todo: ~ relation
            // NetClass::FreeChoice if self.is_live() && self.is_bounded() => None, // todo: requires ILP + trap check
            _ => None,
        }
    }

    /// Whether `target` is reachable from the initial marking.
    ///
    /// Delegates to [`analyze_reachability`](Self::analyze_reachability).
    /// Returns `false` for inconclusive results.
    #[must_use]
    pub fn is_reachable(&self, target: &Marking<u32>) -> bool {
        self.is_efficiently_reachable(target).unwrap_or_else(|| {
            self.analyze_reachability(target).is_reachable()
        })
    }

    /// Analyzes reachability of a target marking with structured evidence.
    ///
    /// Returns [`ReachabilityResult::Reachable`] with a firing sequence,
    /// [`ReachabilityResult::Unreachable`] with a proof, or
    /// [`ReachabilityResult::Inconclusive`] if current algorithms cannot decide.
    ///
    /// Strategy (ascending cost):
    /// 1. **S-nets**: token conservation (exact, polynomial).
    /// 2. **T-nets**: ILP marking equation (exact).
    /// 3. **General**: LP filter → ILP filter → state space exploration.
    ///
    /// For unbounded general nets where LP/ILP filters pass, returns
    /// `Inconclusive` rather than attempting infinite exploration.
    #[must_use]
    pub fn analyze_reachability(&self, target: &Marking<u32>) -> ReachabilityResult {
        let target = self.mapping.decode(target.clone());

        if self.marking == target {
            return ReachabilityProof::FiringSequence(Box::new([])).into();
        }

        // Token conservation: for any S-net every transition has |•t| = |t•| = 1,
        // so M₀(S) = M(S) for all reachable M. A different token sum proves unreachability
        // without requiring strong connectivity or liveness.
        if self.class().is_state_machine() {
            // Accumulate in u64: a u32 fold overflows once a marking's total
            // exceeds u32::MAX (each place count still fits in u32) — panicking in
            // debug or wrapping in release, where a wrap could make differing
            // totals compare equal and slip past this conservation check.
            let initial_sum = token_total(self.marking.iter());
            let target_sum = token_total(target.iter());
            if initial_sum != target_sum {
                return UnreachabilityProof::StateMachineTokenConservation.into();
            }
            // Equal token sum in a live (strongly connected + marked) S-net: any marking
            // with the same sum is reachable (Theorem 5.1.5).
            if self.is_strongly_connected() {
                return ReachabilityProof::LiveStateMachineTokenConservation {
                    marking_sum: initial_sum,
                }.into();
            }
        }

        if self.class().is_marked_graph() && self.is_live() {
            return semi_decision::find_marking_equation_integer_solution(
                &self.dense_net,
                &self.marking,
                &target
            ).map_or_else(
                || UnreachabilityProof::MarkingEquationNoIntegerSolution.into(),
                |solution| {
                    let solution = self.transitions().zip(solution).collect();
                    ReachabilityProof::LiveMarkedGraphMarkingEquationIntegerSolution(solution).into()
                }
            )
        }

        if semi_decision::find_marking_equation_rational_solution(
            &self.dense_net,
            &self.marking,
            &target,
        ).is_none() {
            return UnreachabilityProof::MarkingEquationNoRationalSolution.into();
        }

        // todo: only test ILP if the rational solution is already an integer solution
        if semi_decision::find_marking_equation_integer_solution(
            &self.dense_net,
            &self.marking,
            &target,
        ).is_none() {
            return UnreachabilityProof::MarkingEquationNoIntegerSolution.into();
        }

        let mut explorer = self.explore_coverability(ExplorationOrder::BreadthFirst).core;
        while let Some((_t_idx, node_idx, is_new)) = explorer.explore_next() {
            if !is_new {
                continue;
            }
            let marking = explorer.state_space.marking_at(node_idx);
            if marking.has_omega() {
                return ReachabilityResult::Inconclusive;
            }
            if marking == target {
                let path = explorer.path_from_initial_to(marking)
                    .expect("marking is in graph")
                    .into_iter()
                    .map(|t_idx| self.mapping.transition(t_idx))
                    .collect();
                return ReachabilityProof::FiringSequence(path).into()
            }
        }
        UnreachabilityProof::ExhaustiveSearch.into()
    }
}

/// Total token count of a `u32` marking, accumulated in `u64`.
///
/// Token-conservation reachability compares total token counts. The generic
/// `IdxMarking::sum` / `Marking::total_tokens` helpers fold in `u32`, which
/// overflows once a marking's *total* exceeds `u32::MAX` — even when every
/// individual place count fits in `u32`. That panics in a debug build and, worse,
/// silently wraps in a release build, so a non-conserving target could compare
/// equal to M₀ and be minted a false `reachable` verdict. A marking has at most
/// `2^32` places, each holding at most `u32::MAX < 2^32` tokens, so the true
/// total is always `< 2^64`: a `u64` accumulator is overflow-free for every
/// representable marking.
fn token_total<'a>(counts: impl IntoIterator<Item = &'a u32>) -> u64 {
    counts.into_iter().map(|&tokens| u64::from(tokens)).sum()
}

#[cfg(test)]
mod tests {
    use crate::builder::NetBuilder;
    use crate::class::NetClass;

    #[test]
    fn s_net_reachability_dispatches() {
        let (net, p0, _t0, p1, _t1) = crate::api::system::tests::two_place_cycle();
        let sys = net.with_initial_marking([(p0, 1)]);
        assert!(sys.is_reachable(&[(p1, 1)].into()));
        assert!(sys.is_reachable(&[(p0, 1)].into()));
        assert!(!sys.is_reachable(&[(p0, 2)].into()));
        assert!(!sys.is_reachable(&[].into()));
    }

    #[test]
    fn t_net_reachability_dispatches() {
        let mut b = NetBuilder::new();
        let [p0, p1, p2] = b.add_places();
        let [t0, t1] = b.add_transitions();
        b.add_arc((p0, t0));
        b.add_arc((p1, t0));
        b.add_arcs((t0, p2, t1));
        b.add_arc((t1, p0));
        b.add_arc((t1, p1));
        let net = b.build().unwrap();
        assert_eq!(net.class(), NetClass::MarkedGraph);
        let sys = net.with_initial_marking([(p0, 1), (p1, 1)]);
        assert!(sys.is_reachable(&[(p2, 1)].into()));
        assert!(sys.is_reachable(&[(p0, 1), (p1, 1)].into()));
        assert!(!sys.is_reachable(&[(p1, 1)].into()));
    }

    /// A target whose *total* token count exceeds `u32::MAX` — while each place
    /// count individually fits in `u32` — must never be minted `reachable` on a
    /// token-conserving circuit, and must not panic. Summing the comparison in
    /// `u32` overflows: a panic in debug, or a wrap in release that makes a
    /// differing total compare equal to M₀ (an unsound false positive). Both the
    /// efficient path (`is_reachable`) and the `analyze_reachability`
    /// conservation path are exercised.
    #[test]
    fn reach_token_sum_overflow_no_false_positive() {
        let (net, p0, _t0, p1, _t1) = crate::api::system::tests::two_place_cycle();
        // M₀ total = 1. A circuit conserves tokens, so every reachable marking
        // has total 1.
        let sys = net.with_initial_marking([(p0, 1)]);

        // Target total = 3e9 + 2e9 = 5e9 > u32::MAX; each count is a valid u32.
        // A conserving circuit at total 1 can never reach total 5e9.
        let overflowing_target: crate::marking::Marking<u32> =
            [(p0, 3_000_000_000_u32), (p1, 2_000_000_000_u32)].into();

        // No false positive and no panic on the efficient dispatch path...
        assert!(!sys.is_reachable(&overflowing_target));
        // ...nor on the analyze_reachability token-conservation path.
        assert!(sys.analyze_reachability(&overflowing_target).is_unreachable());
    }

    #[test]
    fn general_net_reachability_fallback() {
        let mut b = NetBuilder::new();
        let [p0, p1, p2] = b.add_places();
        let [t0, t1, t2] = b.add_transitions();
        b.add_arcs((p0, t0, p1));
        b.add_arcs((p0, t1, p2));
        b.add_arcs((p1, t2, p0));
        b.add_arcs((p2, t2, p0));
        let net = b.build().unwrap();
        assert_eq!(net.class(), NetClass::General);
        let sys = net.with_initial_marking([(p0, 1)]);
        assert!(sys.is_reachable(&[(p0, 1)].into()));
        assert!(sys.is_reachable(&[(p1, 1)].into()));
    }
}